def _pdf_font_setup():
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    candidates = [
        ("SimHei", r"C:\Windows\Fonts\simhei.ttf", None),
        ("SimSun", r"C:\Windows\Fonts\simsun.ttc", 0),
        ("MSYH", r"C:\Windows\Fonts\msyh.ttc", 0),
    ]
    for name, path, subfont in candidates:
        try:
            pdfmetrics.registerFont(TTFont(name, path, subfontIndex=subfont) if subfont is not None else TTFont(name, path))
            return name
        except Exception:
            continue
    raise RuntimeError("未找到可用中文字体（simhei/simsun/msyh），无法生成 PDF")


def render_pdf(path: Path, title: str, content: str) -> None:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    font = _pdf_font_setup()
    doc = SimpleDocTemplate(str(path), pagesize=A4)
    title_style = ParagraphStyle("t", fontName=font, fontSize=16, leading=22, spaceAfter=12)
    body_style = ParagraphStyle("b", fontName=font, fontSize=10.5, leading=18)
    story = [Paragraph(title, title_style)]
    for para in content.split("\n\n"):
        if para.strip():
            story.append(Paragraph(para.replace("\n", "<br/>"), body_style))
            story.append(Spacer(1, 6))
    doc.build(story)


def render_xlsx(path: Path, title: str, specs: list[tuple[str, str]]) -> None:
    from openpyxl import Workbook

    wb = Workbook()
    ws = wb.active
    ws.title = "规格参数"
    ws.append(["参数项", "参数值"])
    for k, v in specs:
        ws.append([k, v])
    wb.save(str(path))


def render_docx(path: Path, title: str, content: str) -> None:
    import docx

    d = docx.Document()
    d.add_heading(title, level=1)
    d.add_paragraph(content)
    d.save(str(path))


